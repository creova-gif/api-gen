"""
APIGen TypeScript Client SDK Generator.
Emits a lightweight, zero-dependency TypeScript client SDK with full type definitions
matching the generated OpenAPI specification and Pydantic models.
"""

from typing import List
from apigen.infer import FieldDef, SchemaDef
from apigen.planner import APIPlan


def _ts_type_annotation(f: FieldDef) -> str:
    mapping = {
        "int": "number",
        "float": "number",
        "bool": "boolean",
        "str": "string",
        "datetime": "string",
        "date": "string",
    }
    base = mapping.get(f.python_type, "string")
    if f.enum_values:
        enum_types = " | ".join(f'"{v}"' for v in f.enum_values)
        return enum_types
    if f.nullable:
        return f"{base} | null"
    return base


def generate_typescript_sdk(plan: APIPlan) -> str:
    """Generates a complete, single-file zero-dependency TypeScript client."""
    schema = plan.schema
    res_title = schema.resource_name.capitalize()
    pk = schema.primary_key or "id"

    # TypeScript Interfaces
    fields_ts = []
    create_fields_ts = []
    update_fields_ts = []

    for f in schema.fields:
        ts_type = _ts_type_annotation(f)
        fields_ts.append(f"  {f.name}: {ts_type};")
        if f.name != pk:
            optional_marker = "?" if f.nullable else ""
            create_fields_ts.append(f"  {f.name}{optional_marker}: {ts_type};")
            update_fields_ts.append(f"  {f.name}?: {ts_type};")

    fields_str = "\n".join(fields_ts)
    create_fields_str = "\n".join(create_fields_ts) or "  [key: string]: unknown;"
    update_fields_str = "\n".join(update_fields_ts) or "  [key: string]: unknown;"

    auth_header_logic = ""
    auth_param = ""
    if plan.auth_enabled:
        auth_param = "apiKey?: string; "
        auth_header_logic = """
    if (this.apiKey) {
      headers["X-API-Key"] = this.apiKey;
    }
"""

    return f"""/**
 * {plan.title} - Typed Client SDK.
 * Auto-generated by APIGen Blueprint Engine.
 * Zero external dependencies (uses native fetch).
 */

export interface {res_title} {{
{fields_str}
}}

export interface {res_title}CreateInput {{
{create_fields_str}
}}

export interface {res_title}UpdateInput {{
{update_fields_str}
}}

export interface PaginationMetadata {{
  total: number;
  limit: number;
  offset: number;
}}

export interface {res_title}ListResponse {{
  items: {res_title}[];
  pagination: PaginationMetadata;
}}

export interface {res_title}ListParams {{
  limit?: number;
  offset?: number;
  q?: string;
  [key: string]: unknown;
}}

export interface ClientConfig {{
  baseUrl: string;
  {auth_param}fetch?: typeof fetch;
}}

export class {res_title}Client {{
  private baseUrl: string;
  private apiKey?: string;
  private customFetch: typeof fetch;

  constructor(config: ClientConfig) {{
    this.baseUrl = config.baseUrl.replace(/\\/+$/, "");
    this.apiKey = config.apiKey;
    this.customFetch = config.fetch || globalThis.fetch;
  }}

  private async request<T>(path: string, options: RequestInit = {{}}): Promise<T> {{
    const headers: Record<string, string> = {{
      "Content-Type": "application/json",
      ...(options.headers as Record<string, string>),
    }};
{auth_header_logic}
    const response = await this.customFetch(`${{this.baseUrl}}${{path}}`, {{
      ...options,
      headers,
    }});

    if (!response.ok) {{
      const errorText = await response.text();
      throw new Error(`API Error [${{response.status}}]: ${{errorText}}`);
    }}

    if (response.status === 204) {{
      return null as T;
    }}

    return response.json();
  }}

  /** Health probe check */
  async health(): Promise<{{ status: string; records_count: number }}> {{
    return this.request("/healthz");
  }}

  /** List {schema.plural_name} with pagination and filters */
  async list(params: {res_title}ListParams = {{}}): Promise<{res_title}ListResponse> {{
    const query = new URLSearchParams();
    if (params.limit !== undefined) query.set("limit", String(params.limit));
    if (params.offset !== undefined) query.set("offset", String(params.offset));
    if (params.q !== undefined) query.set("q", params.q);

    for (const [k, v] of Object.entries(params)) {{
      if (!["limit", "offset", "q"].includes(k) && v !== undefined) {{
        query.set(k, String(v));
      }}
    }}

    const qs = query.toString();
    return this.request(`/{schema.plural_name}${{qs ? `?${{qs}}` : ""}}`);
  }}

  /** Get a single {schema.resource_name} by ID */
  async get(id: string | number): Promise<{res_title}> {{
    return this.request(`/{schema.plural_name}/${{encodeURIComponent(id)}}`);
  }}

  /** Create a new {schema.resource_name} */
  async create(payload: {res_title}CreateInput): Promise<{res_title}> {{
    return this.request(`/{schema.plural_name}`, {{
      method: "POST",
      body: JSON.stringify(payload),
    }});
  }}

  /** Update an existing {schema.resource_name} */
  async update(id: string | number, payload: {res_title}UpdateInput): Promise<{res_title}> {{
    return this.request(`/{schema.plural_name}/${{encodeURIComponent(id)}}`, {{
      method: "PATCH",
      body: JSON.stringify(payload),
    }});
  }}

  /** Delete a {schema.resource_name} by ID */
  async delete(id: string | number): Promise<void> {{
    return this.request(`/{schema.plural_name}/${{encodeURIComponent(id)}}`, {{
      method: "DELETE",
    }});
  }}
}}
"""
