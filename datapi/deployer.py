"""
Datapi Multi-Cloud Deployment Generator.
Produces deployment bundles and infrastructure manifests for:
- Fly.io (fly.toml with zero-scaling and health checks)
- AWS App Runner (Terraform HCL with auto-scaling and health checks)
- Google Cloud Run (Terraform HCL)
"""

from pathlib import Path
from typing import List, Optional, Union

from datapi.planner import APIPlan
from datapi.generator import generate_terraform


def generate_fly_config(
    plan: Optional[APIPlan] = None,
    app_name: str = "datapi-service",
    primary_region: str = "iad",
) -> str:
    """
    Emits a production fly.toml for Fly.io with:
    - app = app_name
    - primary_region = primary_region
    - [build] dockerfile = "Dockerfile"
    - [http_service] with internal_port = 8000, force_https = true,
      auto_stop_machines = true, min_machines_running = 0
    - [[services.http_checks]] hitting /healthz
    """
    if app_name is None:
        if plan and getattr(plan, "schema", None) and getattr(plan.schema, "resource_name", None):
            app_name = f"{plan.schema.resource_name.lower()}-api"
        else:
            app_name = "datapi-service"

    env_section = ""
    if plan and getattr(plan, "auth_enabled", False):
        env_section = """
[env]
  PORT = "8000"
  # Set API_KEY via: fly secrets set API_KEY="your-secret-key"
"""

    return f"""# Fly.io deployment configuration generated by Datapi
app = "{app_name}"
primary_region = "{primary_region}"

[build]
  dockerfile = "Dockerfile"

[http_service]
  internal_port = 8000
  force_https = true
  auto_stop_machines = true
  min_machines_running = 0

[[services.http_checks]]
  interval = "15s"
  timeout = "2s"
  grace_period = "5s"
  method = "get"
  path = "/healthz"
  protocol = "http"{env_section}
"""


def generate_aws_manifests(
    plan: Optional[APIPlan] = None,
    service_name: str = "datapi-service",
) -> str:
    """
    Emits Terraform HCL for AWS App Runner (terraform/aws_apprunner.tf):
    - aws_apprunner_service resource block
    - Auto-scaling configuration (min 1, max 5)
    - Port 8000
    - Health check path /healthz
    """
    if service_name is None:
        if plan and getattr(plan, "schema", None) and getattr(plan.schema, "resource_name", None):
            service_name = f"{plan.schema.resource_name.lower()}-api"
        else:
            service_name = "datapi-service"

    service_slug = service_name.replace("-", "_").replace(".", "_")

    auth_env = ""
    if plan and getattr(plan, "auth_enabled", False):
        auth_env = '\n          API_KEY = "REPLACE_WITH_SECRET"'

    return f"""terraform {{
  required_version = ">= 1.5.0"
  required_providers {{
    aws = {{
      source  = "hashicorp/aws"
      version = "~> 5.0"
    }}
  }}
}}

variable "aws_region" {{
  type        = string
  default     = "us-east-1"
  description = "AWS region for deployment"
}}

variable "image_uri" {{
  type        = string
  default     = "public.ecr.aws/aws-containers/hello-app-runner:latest"
  description = "Container image URI for App Runner service"
}}

provider "aws" {{
  region = var.aws_region
}}

# Auto-Scaling Configuration for AWS App Runner (Min: 1, Max: 5)
resource "aws_apprunner_auto_scaling_configuration_version" "{service_slug}_scaling" {{
  auto_scaling_configuration_name = "{service_name}-scaling"
  max_concurrency                 = 100
  max_size                        = 5
  min_size                        = 1

  tags = {{
    ManagedBy = "datapi"
    Service   = "{service_name}"
  }}
}}

# AWS App Runner Service
resource "aws_apprunner_service" "{service_slug}" {{
  service_name = "{service_name}"

  auto_scaling_configuration_arn = aws_apprunner_auto_scaling_configuration_version.{service_slug}_scaling.arn

  source_configuration {{
    auto_deployments_enabled = false

    image_repository {{
      image_identifier      = var.image_uri
      image_repository_type = "ECR_PUBLIC"

      image_configuration {{
        port = "8000"
        runtime_environment_variables = {{
          PORT = "8000"{auth_env}
        }}
      }}
    }}
  }}

  health_check_configuration {{
    protocol            = "HTTP"
    path                = "/healthz"
    interval            = 10
    timeout             = 5
    healthy_threshold   = 1
    unhealthy_threshold = 5
  }}

  tags = {{
    ManagedBy = "datapi"
    Service   = "{service_name}"
  }}
}}

output "service_url" {{
  value       = "https://${{aws_apprunner_service.{service_slug}.service_url}}"
  description = "Public URL of deployed AWS App Runner API"
}}
"""


def generate_cloudrun_manifests(
    plan: Optional[APIPlan] = None,
    service_name: str = "datapi-service",
) -> str:
    """
    Emits Terraform HCL for Google Cloud Run (v2).
    """
    if service_name is None:
        if plan and getattr(plan, "schema", None) and getattr(plan.schema, "resource_name", None):
            service_name = f"{plan.schema.resource_name.lower()}-api"
        else:
            service_name = "datapi-service"

    auth_enabled = bool(plan and getattr(plan, "auth_enabled", False))
    return generate_terraform(service_name, auth_enabled=auth_enabled)


def generate_deployment_bundle(
    plan: APIPlan,
    target: str = "all",
    out_dir: Union[str, Path] = Path("."),
    service_name: Optional[str] = None,
) -> List[str]:
    """
    Generates all deployment files based on target (`cloudrun`, `fly`, `aws`, `all`).
    Returns list of paths of created files.
    """
    target_clean = (target or "all").strip().lower()
    valid_targets = {"cloudrun", "fly", "aws", "all"}
    if target_clean not in valid_targets:
        raise ValueError(
            f"Unsupported deployment target: '{target}'. Supported targets: {', '.join(sorted(valid_targets))}"
        )

    out_path = Path(out_dir)
    out_path.mkdir(parents=True, exist_ok=True)

    if service_name is None:
        if plan and getattr(plan, "schema", None) and getattr(plan.schema, "resource_name", None):
            service_name = f"{plan.schema.resource_name.lower()}-api"
        else:
            service_name = "datapi-service"

    generated: List[str] = []

    if target_clean in ("fly", "all"):
        fly_config = generate_fly_config(plan, app_name=service_name)
        fly_path = out_path / "fly.toml"
        fly_path.write_text(fly_config, encoding="utf-8")
        generated.append(str(fly_path))

    if target_clean in ("aws", "all"):
        tf_dir = out_path / "terraform"
        tf_dir.mkdir(parents=True, exist_ok=True)
        aws_hcl = generate_aws_manifests(plan, service_name=service_name)
        aws_path = tf_dir / "aws_apprunner.tf"
        aws_path.write_text(aws_hcl, encoding="utf-8")
        generated.append(str(aws_path))

    if target_clean in ("cloudrun", "all"):
        tf_dir = out_path / "terraform"
        tf_dir.mkdir(parents=True, exist_ok=True)
        cr_hcl = generate_cloudrun_manifests(plan, service_name=service_name)
        cr_path = tf_dir / "main.tf"
        cr_path.write_text(cr_hcl, encoding="utf-8")
        generated.append(str(cr_path))

    return generated
