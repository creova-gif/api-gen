def _py_type_annotation(f: FieldDef) -> str:
    mapping = {
        "int": "int",
        "float": "float",
        "bool": "bool",
        "str": "str",
        "datetime": "str",
        "date": "str",
    }
    base = mapping.get(f.python_type, "str")
    if f.nullable:
        return f"Optional[{base}]"
    return base


